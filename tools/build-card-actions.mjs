// Builds scripts/games/card_actions.js: typed actions for the free-text ("custom") lines of the ability cards, for later automation of the turn.
// Source: card-code-current/<folder>/<class>-ability-cards.code.json (the owner's checked card code is not changed), matched to the app's card ids
// by tools/lib/cardcode.mjs. Only lines that tools/lib/parse-text.mjs understands completely are written; the rest stays free text.
//
// Usage: node tools/build-card-actions.mjs [class code ...]       default: every class of scripts/games/gh2_classes.js
//        node tools/build-card-actions.mjs --report [class code ...]   also lists the lines of the parsed kinds that were not understood
//
// Output: CARD_ACTIONS[card id] = { t: [...], b: [...] }, one entry per parsed line of the top half (t) and the bottom half (b):
//   { n: ordinal of the free-text line in its half (0 is the first), text: the line as in the card code, a: [typed actions] }
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, eachCard } from './lib/cardcode.mjs';
import { parseLine } from './lib/parse-text.mjs';

const OUT = join(ROOT, 'scripts', 'games', 'card_actions.js');

// the free-text lines of a half, in reading order (the same walk as build-turn-templates.mjs: actions inside groups and sub-actions too)
function customTexts(half) {
  const out = [];
  const walk = a => {
    if (Array.isArray(a)) { a.forEach(walk); return; }
    if (!a || typeof a !== 'object') return;
    if (a.type === 'custom' && a.text) out.push(a.text);
    walk(a.subActions);
    walk(a.actions);
  };
  walk(half && half.actions);
  return out;
}

// lines that look like one of the parsed kinds: used for the report of what was not understood
const KINDS = { xp: /%xp%/, recover: /%recover%/i, create: /\b(create|place)\b.*(tile|trap|%rift%|%tear%|%fh-shadow%)/i };

function main() {
  const args = process.argv.slice(2);
  const report = args.includes('--report');
  let classes = args.filter(a => a !== '--report');
  if (!classes.length) classes = [...readFileSync(join(ROOT, 'scripts', 'games', 'gh2_classes.js'), 'utf8').matchAll(/"code":"([a-z0-9]+)","name"/g)].map(m => m[1]);
  const out = {};
  const stats = { cards: 0, custom: 0, parsed: 0 };
  const missed = { xp: [], recover: [], create: [] };
  const { missing, failed } = eachCard(classes, ({ id, json }) => {
    stats.cards++;
    const entry = {};
    for (const [key, half] of [['t', json.top], ['b', json.bottom]]) {
      const lines = [];
      customTexts(half).forEach((text, n) => {
        stats.custom++;
        const a = parseLine(text);
        if (a) { stats.parsed++; lines.push({ n, text, a }); return; }
        for (const [kind, re] of Object.entries(KINDS)) if (re.test(text)) missed[kind].push(text);
      });
      if (lines.length) entry[key] = lines;
    }
    if (entry.t || entry.b) out[id] = entry;
  });
  if (failed) process.exitCode = 1;
  const body = Object.entries(out).map(([id, v]) => `  ${id}: ${JSON.stringify(v)}`).join(',\n');
  const head = '// GENERATED by tools/build-card-actions.mjs from card-code-current. Do not edit by hand.\n// Typed actions for the free-text lines of the ability cards that the parser (tools/lib/parse-text.mjs) understands completely, by card id:\n// t = top half, b = bottom half, each line { n: ordinal of the free-text line in the half, text, a: typed actions }. Other lines stay free text.\n\n';
  writeFileSync(OUT, `${head}export const CARD_ACTIONS = {\n${body}\n};\n`);
  console.log(`${stats.cards} cards, ${stats.custom} free-text lines, ${stats.parsed} parsed into typed actions, ${Object.keys(out).length} cards with typed lines${missing ? `, ${missing} cards without card code` : ''}`);
  if (report) {
    for (const [kind, list] of Object.entries(missed)) {
      const counts = new Map();
      for (const t of list) counts.set(t, (counts.get(t) || 0) + 1);
      console.log(`\n${kind}: ${list.length} lines not understood (${counts.size} different)`);
      for (const [t, c] of [...counts].sort((x, y) => y[1] - x[1]).slice(0, 40)) console.log(`  ${c} x ${t.length > 160 ? t.slice(0, 160) + '...' : t}`);
    }
  }
}

main();
