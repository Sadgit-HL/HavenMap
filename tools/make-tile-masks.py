"""Derive the floor hexes of the Gloomhaven 2e map tiles from the tile images.

Writes scripts/games/gh2_tile_masks.js (GENERATED). Run from the repo root: python tools/make-tile-masks.py

Method: a tile image is placed 1:1 on the board with its anchor hex centre at (left, top) pixels from the image corner (scripts/games/gh.js TILE_ROWS,
scripts/render.js renderTiles). The images have an alpha channel: outside the printed hexes the pixels are transparent, but the art border around the
hexes is opaque, so the test uses the whole hex: a hex is floor when at least 93% of its area (88% of the hex size) is opaque. Hexes cut by the image
edge count as transparent there.

Each mask is a list of [q, r]: q = columns right of the anchor hex (negative = left), r = rows down. The hex centre is
x = anchorX + 0.75 * 90 * q, y = anchorY + 78 * (r + q / 2), the same grid as scripts/hex.js (flat top, 90 wide, 78 high).
Masks are for angle 0; a placed tile is rotated about its anchor hex.

Frosthaven tiles are not covered: 46 of 76 have no alpha channel (see docs/ai/monster-automation.md).
"""
import json, math, os, re, sys
from PIL import Image

W, H = 90.0, 78.0
R = W / 2
THRESHOLD = 0.93
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def tile_rows():
    src = open(os.path.join(ROOT, 'scripts/games/gh.js'), encoding='utf-8').read()
    return [(m.group(2), int(m.group(3)), int(m.group(4)))
            for m in re.finditer(r"id:\s*(\d+),\s*title:\s*'([^']+)',\s*left:\s*(-?\d+),\s*top:\s*(-?\d+)", src)]


def inside(dx, dy):
    r = R * 0.88
    dx, dy = abs(dx), abs(dy)
    return dy <= (math.sqrt(3) / 2) * r and dx * (math.sqrt(3) / 2) + dy * 0.5 <= (math.sqrt(3) / 2) * r


SAMPLES = [(dx, dy) for dx in range(-40, 41, 5) for dy in range(-36, 37, 5) if inside(dx, dy)]


def floor_hexes(alpha, ax, ay):
    w, h = alpha.size
    px = alpha.load()
    out = []
    for q in range(-12, 13):
        for r in range(-12, 13):
            cx = ax + 0.75 * W * q
            cy = ay + H * (r + q / 2)
            if cx < -R or cy < -H or cx > w + R or cy > h + H:
                continue
            n = sum(1 for dx, dy in SAMPLES if 0 <= int(cx + dx) < w and 0 <= int(cy + dy) < h and px[int(cx + dx), int(cy + dy)] > 128)
            if n / len(SAMPLES) >= THRESHOLD:
                out.append([q, r])
    return sorted(out)


def main():
    masks = {}
    for name, ax, ay in tile_rows():
        path = os.path.join(ROOT, 'images/tiles/gh2', name + '.webp')
        if not os.path.exists(path):
            print('no image for tile', name, file=sys.stderr)
            continue
        masks[name] = floor_hexes(Image.open(path).convert('RGBA').getchannel('A'), ax, ay)
    lines = [
        '// GENERATED by tools/make-tile-masks.py from the tile images (images/tiles/gh2). Do not edit by hand.',
        '// Floor hexes of the Gloomhaven 2e map tiles at angle 0: [q, r] = columns right of and rows below the anchor hex; centre = anchor + (0.75 * 90 * q, 78 * (r + q / 2)).',
        '',
        'export const GH2_TILE_MASKS = {',
    ]
    for name in masks:
        lines.append(f"  '{name}': {json.dumps(masks[name], separators=(',', ':'))},")
    lines += ['};', '']
    open(os.path.join(ROOT, 'scripts/games/gh2_tile_masks.js'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print(len(masks), 'tiles,', sum(len(v) for v in masks.values()), 'hexes')


main()
