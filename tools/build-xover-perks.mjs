// Writes scripts/games/perks_xover.js from tools/jotl-xover-perks.json: the perks of Cephalofair's updated (crossover) character
// sheets, which replace the perk lists of scripts/games/perks.js for those classes (scripts/amd/perkData.js merges the two).
// The entries have the shape of perks.js (tools/extract-perks.mjs): { index, text, removes, adds }, one entry per box; decorated
// faces are decoded with tools/perks-decode.mjs, as there.
//
// Usage: node tools/build-xover-perks.mjs

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { decodeSlug, normalizeValue } from './perks-decode.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(__dirname, 'jotl-xover-perks.json');
const OUT = path.join(ROOT, 'scripts/games/perks_xover.js');
const BASE = { '+0': '+0', '+1': '+1', '+2': '+2', '+3': '+3', '+4': '+4', '-1': '-1', '-2': '-2' };

function card(tok) {
  if (BASE[tok]) return { kind: 'base', value: BASE[tok] };
  if (tok.startsWith('u:')) { const code = tok.slice(2); return { kind: 'unique', code, art: { kind: 'fa', ref: `unique/${code}` } }; }
  const r = decodeSlug('perks/' + tok);
  if (r.error) throw new Error(`decode failed for "${tok}": ${r.error} (leftover "${r.rest}")`);
  return {
    kind: 'shared',
    value: normalizeValue(r.value),
    tokens: r.tokens.map(t => ({ word: t.word, cat: t.cat, icon: t.icon, key: t.key, amount: t.amount })),
    art: { kind: 'psd', ref: tok },
  };
}

const src = JSON.parse(fs.readFileSync(SRC, 'utf-8'));
const out = {};
for (const [edition, classes] of Object.entries(src)) {
  if (edition.startsWith('_')) continue;
  out[edition] = {};
  for (const [name, lines] of Object.entries(classes)) {
    const list = [];
    for (const l of lines) {
      for (let k = 0; k < (l.n || 1); k++) list.push({ index: list.length, text: l.text || null, removes: (l.removes || []).map(card), adds: (l.adds || []).map(card) });
    }
    const boxes = list.reduce((s, p) => s + (/^\s*\[double\]/i.test(p.text || '') ? 2 : 1), 0);
    if (boxes !== 15) console.warn(`${edition} ${name}: ${boxes} boxes (a class sheet has 15)`);
    out[edition][name] = list;
    console.log(`${edition} ${name}: ${list.length} entries, ${boxes} boxes`);
  }
}

const header = `// GENERATED by tools/build-xover-perks.mjs from tools/jotl-xover-perks.json. Do not hand-edit: change the JSON and re-run.
// Perks of Cephalofair's updated (crossover) character sheets, transcribed from the sheets. They replace the perk lists of
// scripts/games/perks.js for these classes (merged in scripts/amd/perkData.js). Same entry shape as perks.js.
`;
fs.writeFileSync(OUT, header + `export const PERKS_XOVER = ${JSON.stringify(out, null, 2)};\n`);
console.log('written', OUT);
