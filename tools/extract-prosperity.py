"""Extract the Gloomhaven 2e prosperity data from Gloomhaven Secretariat's gh2e data (AGPL-3.0) into
scripts/games/gh2_prosperity.js (ES module, generated, do not hand-edit).

  PROSPERITY_SECTIONS  { "<prosperity level>": "<section to read>" }   from campaign.json prosperitySections
  PROSPERITY_ITEMS     { "<prosperity level>": [item ids] }            from items.json unlockProsperity
  IMBUEMENT_SECTIONS   { "<imbuement box>": "<section to read>" }        from campaign.json imbuementSections

Item ids equal the ids in gh2_items.js (the Card DB numbering matches the Secretariat's).

Usage:  python -I tools/extract-prosperity.py [path/to/gloomhavensecretariat/data/gh2e]
"""
import json
import os
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT = os.path.join('D:' + os.sep, 'github', 'gloomhavensecretariat', 'data', 'gh2e')
OUT = os.path.join(ROOT, 'scripts', 'games', 'gh2_prosperity.js')
# Items the Secretariat data lists with a prosperity level that do not belong in the shop (116 Fated Verses is the only item
# above 64 with one; removed on request).
EXCLUDE = {116}
# The Secretariat keys prosperitySections by the tick count of its level thresholds (GH2E_PROSPERITY_STEPS in
# src/app/game/model/data/EditionData.ts); the step at index i is the one below level i + 2, and its label file names
# the sections "Prosperity 3" (48.2), 4 (54.2), 5 (16.5) and 6 (62.3). The section is read on reaching that level.
GH2E_PROSPERITY_STEPS = [4, 11, 21, 32, 44, 58, 73, 88]


def main():
    base = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    with open(os.path.join(base, 'campaign.json'), encoding='utf-8') as f:
        camp = json.load(f)
    sections = camp['prosperitySections']
    imbuement = {int(k): v for k, v in camp['imbuementSections'].items()}
    with open(os.path.join(base, 'items.json'), encoding='utf-8') as f:
        items = json.load(f)
    by_level = defaultdict(list)
    for it in items:
        lv = it.get('unlockProsperity')
        if lv and it['id'] not in EXCLUDE:
            by_level[int(lv)].append(it['id'])
    sec = {GH2E_PROSPERITY_STEPS.index(int(k)) + 2: v for k, v in sections.items()}
    lines = [
        '// GENERATED by tools/extract-prosperity.py from Gloomhaven Secretariat gh2e data (AGPL-3.0). Do not edit by hand.',
        '// Prosperity track: the section to read when a checkmark is ticked, and the items each prosperity level unlocks.',
        '',
        'export const PROSPERITY_SECTIONS = ' + json.dumps({str(k): sec[k] for k in sorted(sec)}) + ';',
        '',
        'export const IMBUEMENT_SECTIONS = ' + json.dumps({str(k): imbuement[k] for k in sorted(imbuement)}) + ';',
        '',
        'export const PROSPERITY_ITEMS = {',
    ]
    for lv in sorted(by_level):
        lines.append(f'  {lv}: {json.dumps(sorted(by_level[lv]))},')
    lines += ['};', '']
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('gh2_prosperity.js', len(sec), 'sections,', sum(len(v) for v in by_level.values()), 'items')


main()
