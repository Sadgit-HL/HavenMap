#!/usr/bin/env python3
"""Extracts the BGG forum icon codes of the playmat mockup (the sorted icon blocks of the BGG codes modal) into
scripts/campaign/bggIcons.js. The icon names, groups, order, image paths and [ImageID=...] codes are maintained in the mockup
(campaign/mockups/merc-6-playmat-v2.html); rerun this tool after changing them.

Usage: python tools/extract-bgg-icons.py   (writes scripts/campaign/bggIcons.js, GENERATED, do not edit by hand)
"""
import json, os, re

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
src = open(os.path.join(root, 'campaign', 'mockups', 'merc-6-playmat-v2.html'), encoding='utf-8').read()
a = src.index('<div class="bgg-icons">')
b = src.index('<div class="bnrsec"', a)
html = src[a:b]
groups = []
for m in re.finditer(r'<div class="bgg-block"><h4>([^<]*)</h4><div class="bgg-row">(.*?)</div></div>', html, re.S):
    icons = []
    for bm in re.finditer(r'<button type="button" class="bgg-ic[^"]*"([^>]*)>(.*?)</button>', m.group(2), re.S):
        attrs, inner = bm.group(1), bm.group(2)
        code = re.search(r'data-code="([^"]*)"', attrs)
        title = re.search(r'title="([^":]*):', attrs)
        img = re.search(r'<img([^>]*)>', inner)
        if not (code and title and img): continue
        src_img = re.search(r'src="([^"]*)"', img.group(1)).group(1).replace('../../images/', '../images/')
        icons.append({'n': title.group(1), 'c': code.group(1), 'img': src_img, **({'inv': 1} if 'class="inv"' in img.group(1) else {})})
    groups.append({'h': m.group(1), 'icons': icons})

out = os.path.join(root, 'scripts', 'campaign', 'bggIcons.js')
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// GENERATED by tools/extract-bgg-icons.py from campaign/mockups/merc-6-playmat-v2.html. Do not edit by hand.\n')
    f.write('// BGG forum icons for the BGG codes modal: groups in display order, each icon { n: name, c: code to copy, img: image path from the campaign page }.\n\n')
    f.write('export const BGG_ICON_GROUPS = [\n')
    for g in groups:
        f.write('  { h: ' + json.dumps(g['h']) + ', icons: [\n')
        for i in g['icons']:
            f.write('    ' + json.dumps(i, ensure_ascii=False) + ',\n')
        f.write('  ] },\n')
    f.write('];\n')
print('wrote', os.path.normpath(out), sum(len(g['icons']) for g in groups), 'icons in', len(groups), 'groups')
