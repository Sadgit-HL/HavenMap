#!/usr/bin/env python3
"""Builds campaign/playmat.css from the playmat mockup (campaign/mockups/merc-6-playmat-v2.html and mock.css).

Only the rules of the playmat itself are taken (top bar, item shelf, zones, cards, hand, piles, spin box, hover zoom); the
modals and everything else of the mockup stay out. Every selector is scoped under `.pm` (the root element of the playmat in the
campaign page) so nothing leaks into the rest of the page; `body[data-z...]` rules of the mockup become `.pm[data-z...]`.

Usage: python tools/build-playmat-css.py   (writes campaign/playmat.css, GENERATED, do not edit by hand)
"""
import os, re

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
mock = os.path.join(root, 'campaign', 'mockups')
src = open(os.path.join(mock, 'merc-6-playmat-v2.html'), encoding='utf-8').read()
blocks = [m.group(1) for m in re.finditer(r'<style>([\s\S]*?)</style>', src) if 'embed mode' not in m.group(1)]
blocks.insert(0, open(os.path.join(mock, 'mock.css'), encoding='utf-8').read())
css = '\n'.join(blocks)
css = re.sub(r'/\*[\s\S]*?\*/', '', css)
css = re.sub(r'@import[^;]*;', '', css)

# first class (or tag) of a selector must be in this list for the rule to be taken
KEEP = set('''stage6 hud portrait who namerow sub chips chip sep lvl xp xprow xplab xpto xpbar stat counters grp bggseg bggb gear sp spc edv edin
shelf6 it itbar itbadge board6 toprow zone zlabel activelist ac inib pini slot6 slotcard slotempty flipcard flipinner face cardback backlabel realback
hand6 hbar hctl sortgrp btn6 fan6 piles6 pile6 pilecard pilerow6 hint tk tkh ctr target seg setwrap
dock mbtn mmodal mmodalbox mmodalx matflip codelist coderow bgg-icons bgg-row bgg-block bgg-ic bnrsec bnrgrid bnrtile bnrnote bnrnoimg
histbar hlist hrow hz ha hm hempty delx addrow mrow enhtable enhprice enhempty
jbox jtab jtabs pqdock pqcard pqside pqreq pqc pqcheck pqdeck pqdl pqchip pqrow pqoffer pqpick bgcards bgcard mdbar mdprev mdview notesarea notespane rollbtn'''.split())

def split_rules(text):
    """Top level rules as (prelude, body); at-rule bodies are kept as text."""
    out, i, n = [], 0, len(text)
    while i < n:
        j = text.find('{', i)
        if j < 0: break
        prelude = text[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            depth += {'{': 1, '}': -1}.get(text[k], 0)
            k += 1
        out.append((prelude, text[j + 1:k - 1]))
        i = k
    return out

def scope(sel):
    sel = sel.strip()
    if not sel: return None
    if sel.startswith(('html', ':root', '*', '@')): return None
    sel = re.sub(r'^body\[', '.pm[', sel)
    if sel.startswith('body'): return None
    if sel.startswith('.pm['): return sel
    first = re.match(r'[.#]?([a-zA-Z0-9_-]+)', sel)
    if not first or first.group(1) not in KEEP: return None
    return '.pm ' + sel

def rule(prelude, body):
    sels = [scope(s) for s in re.split(r',(?![^\[]*\])(?![^(]*\))', prelude)]
    sels = [s for s in sels if s and not re.search(r'\.over(?![-\w])', s)]            # no drop zone highlight while dragging (the mockup shows none)
    if not sels: return ''
    # a `body[data-z...] .x` rule may name a class we do not keep: check the class after the attribute selector
    keep = []
    for s in sels:
        m = re.match(r'\.pm\[[^\]]*\]\s*([.#]?[a-zA-Z0-9_-]+)?', s)
        if s.startswith('.pm[') and m and m.group(1) and m.group(1).lstrip('.#') not in KEEP: continue
        keep.append(s)
    return (', '.join(keep) + '{' + body.strip() + '}\n') if keep else ''

parts = []
for prelude, body in split_rules(css):
    if prelude.startswith('@media'):
        inner = ''.join(rule(p, b) for p, b in split_rules(body))
        if inner: parts.append(prelude + '{' + inner + '}\n')
    elif prelude.startswith('@keyframes'):
        parts.append(prelude + '{' + body + '}\n')
    elif prelude.startswith('@'):
        continue
    else:
        r = rule(prelude, body)
        if r: parts.append(r)


EXTRA = """
/* campaign page additions (not in the mockup) */
.pm .stage6{grid-template-columns:150px minmax(0,1fr) 112px 64px;height:calc(100vh - 150px);min-height:640px}
.pm .noimg{display:flex;align-items:center;justify-content:center;text-align:center;padding:6px;font-size:12px;color:var(--muted);border:1px solid var(--line);border-radius:6px;background:#1c1711;aspect-ratio:5/7}
.pm .hbar .over-limit{color:#e08a7a}
.pm .fan6 .ac.ins-before{box-shadow:-5px 0 0 var(--accent)}.pm .fan6 .ac.ins-after{box-shadow:5px 0 0 var(--accent)}
.pm .edv{cursor:text}.pm .edin{width:64px}
.pm .mmodal{z-index:300}.pm .hrow small{color:var(--muted);margin-left:6px}.pm .matflip img{max-width:100%;cursor:pointer}
.oldsheet{margin-top:14px}.oldsheet>summary{cursor:pointer;color:var(--muted);padding:6px 2px}
"""

head = '''/* GENERATED by tools/build-playmat-css.py from campaign/mockups/merc-6-playmat-v2.html and mock.css. Do not edit by hand.
   The playmat of the Mercenaries tab: every selector is scoped under .pm. Rules for the modals are not included. */
.pm{--bg:#16130f;--panel:#231d17;--line:#3a3026;--text:#ecdfc8;--muted:#a89a82;--accent:#c7a44a;--ok:#7fb069;--info:#6aa9d8;--warn:#d6a03c;color:var(--text);font:14px/1.35 system-ui,Segoe UI,Roboto,sans-serif}
.pm *{box-sizing:border-box}
'''
open(os.path.join(root, 'campaign', 'playmat.css'), 'w', encoding='utf-8', newline='\n').write(head + ''.join(parts) + EXTRA)
print('wrote campaign/playmat.css', len(parts), 'rule groups')
