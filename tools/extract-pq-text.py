#!/usr/bin/env python3
"""Extract the GH2 personal quest names and requirements from the Gloomhaven Secretariat data.

Source (AGPL-3.0, names and requirement counters only): <secretariat>/data/gh2e/personal-quests.json,
<secretariat>/data/gh2e/label/en.json and <secretariat>/data/gh2e/items.json.
Output: scripts/games/gh2_pq_text.js  (GENERATED, do not edit by hand).

Usage: python tools/extract-pq-text.py [path to gloomhavensecretariat, default D:/github/gloomhavensecretariat]
"""
import json, os, re, sys

root = sys.argv[1] if len(sys.argv) > 1 else 'D:/github/gloomhavensecretariat'
data = os.path.join(root, 'data', 'gh2e')
labels = json.load(open(os.path.join(data, 'label', 'en.json'), encoding='utf-8'))['personalQuest']['gh2e']
quests = json.load(open(os.path.join(data, 'personal-quests.json'), encoding='utf-8'))
items = {str(i['id']): i['name'] for i in json.load(open(os.path.join(data, 'items.json'), encoding='utf-8'))}

SLOTS = {'head': 'Head', 'body': 'Body', 'legs': 'Legs', 'onehand': 'One-hand', 'twohand': 'Two-hand', 'small': 'Small'}

def resolve(text):
    # an item written as "%data.items.gh2e-N% %game.itemFh.N%" is just the item name
    text = re.sub(r'%data\.items\.gh2e-(\d+)% %game\.itemFh\.\d+%', lambda m: items.get(m.group(1), 'item ' + m.group(1)), text)
    text = re.sub(r'%game\.itemFh\.(\d+)%', lambda m: items.get(m.group(1), 'item ' + m.group(1)), text)
    text = re.sub(r'%game\.section:([\d.]+)%', r'section \1', text)
    text = re.sub(r'%game\.scenario:(\d+)%', r'scenario \1', text)
    text = re.sub(r'%game\.damage:(\d+)%', r'damage \1', text)
    text = text.replace('%game.damage%', 'damage').replace('%game.experience%', 'XP').replace('%game.checkmark%', 'checkmarks')
    text = text.replace('%game.element.wild%', 'Wild element').replace('%game.condition.poison%', 'Poison')
    text = re.sub(r'%game\.items\.slots\.(\w+)%', lambda m: SLOTS.get(m.group(1), m.group(1)), text)
    left = re.findall(r'%[^%]*%', text)
    if left:
        print('unresolved token(s):', left, file=sys.stderr)
    return text

out = {}
for q in quests:
    cid = q['cardId']
    lab = labels[cid]
    reqs = []
    for r in q['requirements']:
        m = re.fullmatch(r'%data\.personalQuest\.gh2e\.\d+\.(\d+)%', r['name'])   # label reference, else the name is literal text
        text = lab[m.group(1)] if m else r['name']
        reqs.append({'t': resolve(text), 'n': r.get('counter', 1), 'after': [x - 1 for x in r.get('requires', [])]})
    out['PQ' + cid] = {'name': lab[''], 'reqs': reqs}

dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'scripts', 'games', 'gh2_pq_text.js')
with open(dest, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// GENERATED by tools/extract-pq-text.py from the Gloomhaven Secretariat data (AGPL-3.0). Do not edit by hand.\n')
    f.write('// GH2 personal quests: name and requirements. n = counter target, after = indexes of requirements that must be complete first.\n\n')
    f.write('export const GH2_PQ = {\n')
    for k, v in out.items():
        f.write('  ' + json.dumps(k) + ': ' + json.dumps(v, ensure_ascii=False) + ',\n')
    f.write('};\n')
print('wrote', os.path.normpath(dest), len(out), 'quests')
