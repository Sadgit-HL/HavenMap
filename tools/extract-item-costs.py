"""Write scripts/games/gh2_item_costs.js: the gold cost of each GH2E item, from the Gloomhaven Secretariat data (gh2e/items.json).
Items are matched by number (QM items and Frosthaven / Mercenary Pack solo items have no cost and are not in the table).

Usage:  python -I tools/extract-item-costs.py [path/to/gh2e/items.json]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join('D:' + os.sep, 'github', 'gloomhavensecretariat', 'data', 'gh2e', 'items.json')
OUT = os.path.join(ROOT, 'scripts', 'games', 'gh2_item_costs.js')

with open(SRC, encoding='utf-8') as f:
    costs = {i['id']: i['cost'] for i in json.load(f) if isinstance(i.get('id'), int) and isinstance(i.get('cost'), int)}
body = ',\n'.join(f'  {k}: {costs[k]}' for k in sorted(costs))
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// GENERATED by tools/extract-item-costs.py from the Gloomhaven Secretariat data (data/gh2e/items.json). Do not edit by hand.\n'
            '// Gold cost by GH2E item number.\n\nexport const ITEM_COSTS = {\n' + body + '\n};\n')
print(os.path.basename(OUT), len(costs))
