// Extracts class perk lists for FH, GH2E, JotL and MP from FrosthavenAssistant's edition data
// (Tarmslitaren/FrosthavenAssistant, AGPLv3 code; images cleared for this non-profit app per the
// owner, see docs/HANDOVER.md) and writes scripts/games/perks.js.
//
// Source repo path is hard-coded below: a local clone at the given location, not committed here.
// Re-run after re-cloning or updating that checkout: `node tools/extract-perks.mjs`.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { decodeSlug, normalizeValue } from './perks-decode.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const EDITIONS_DIR = path.resolve(
  REPO_ROOT,
  '../asset-backups/amd/FrosthavenAssistant/frosthaven_assistant/assets/data/editions'
);
const OUT_FILE = path.join(REPO_ROOT, 'scripts/games/perks.js');

// Edition JSON filename -> short key used in our data.
const EDITIONS = {
  'Frosthaven.json': 'FH',
  'Gloomhaven 2nd Edition.json': 'GH2E',
  'Jaws of the Lion.json': 'JotL',
  'Mercenary Packs.json': 'MP',
};

const BASE_CARDS = new Set(['plus0', 'plus1', 'plus2', 'plus3', 'plus4', 'minus1', 'minus2', 'nullAttack']);

function resolveToken(tok) {
  if (BASE_CARDS.has(tok)) {
    return { kind: 'base', value: tok === 'nullAttack' ? 'null' : normalizeValue(tok) };
  }
  if (tok.startsWith('perks/unique/')) {
    const code = tok.slice('perks/unique/'.length);
    return { kind: 'unique', code, art: { kind: 'fa', ref: `unique/${code}` } };
  }
  if (tok.startsWith('perks/')) {
    const r = decodeSlug(tok);
    if (r.error) throw new Error(`decode failed for "${tok}": ${r.error} (leftover "${r.rest}")`);
    return {
      kind: 'shared',
      value: normalizeValue(r.value),
      tokens: r.tokens.map(t => ({ word: t.word, cat: t.cat, icon: t.icon, key: t.key, amount: t.amount })),
      art: { kind: 'psd', ref: tok.replace(/^perks\//, '') },
    };
  }
  throw new Error(`unrecognized token: "${tok}"`);
}

if (!fs.existsSync(EDITIONS_DIR)) {
  console.error(`Edition data not found at ${EDITIONS_DIR}`);
  console.error('Clone Tarmslitaren/FrosthavenAssistant into asset-backups/amd first.');
  process.exit(1);
}

const out = {};
for (const [file, editionKey] of Object.entries(EDITIONS)) {
  const d = JSON.parse(fs.readFileSync(path.join(EDITIONS_DIR, file), 'utf-8'));
  out[editionKey] = {};
  for (const c of d.classes) {
    out[editionKey][c.name] = c.perks.map((p, i) => ({
      index: i,
      text: p.text || null,
      removes: (p.removes || []).map(resolveToken),
      adds: (p.adds || []).map(resolveToken),
    }));
  }
}

const classCounts = Object.fromEntries(
  Object.entries(out).map(([ed, classes]) => [ed, Object.keys(classes).length])
);
const totalPerks = Object.values(out).flatMap(classes => Object.values(classes)).reduce((a, p) => a + p.length, 0);
console.log('classes per edition:', classCounts);
console.log('total perk entries:', totalPerks);

const header = `// Generated by tools/extract-perks.mjs from FrosthavenAssistant edition data
// (Tarmslitaren/FrosthavenAssistant, AGPLv3). Do not hand-edit: re-run the script instead.
//
// PERKS[edition][className] = array of perk entries, one per checkbox on the class's perk sheet
// (duplicated entries mean the perk can be taken twice). Each entry: { index, text, removes, adds }
// where removes/adds are arrays of cards:
//   { kind: 'base', value }                 -- a plain +0/+1/.../-2/null card
//   { kind: 'shared', value, tokens, art }  -- decorated card; tokens decode the effect icons to
//                                              compose (see docs/hero-modifier-faces.md); art.ref
//                                              is the FrosthavenAssistant perk slug for reference
//   { kind: 'unique', code, art }           -- one-off per-class card with no icon decomposition;
//                                              render from the baked FrosthavenAssistant image at
//                                              assets/images/attack/perks/unique/<code>.png
// 'text' is set only for perks with special wording not implied by the cards alone.
`;
const body = `export const PERKS = ${JSON.stringify(out, null, 2)};\n`;
fs.writeFileSync(OUT_FILE, header + body);
console.log('written', OUT_FILE);
