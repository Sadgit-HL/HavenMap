"""Extract the Gloomhaven 2e reputation unlocks from Gloomhaven Secretariat's gh2e data (AGPL-3.0) into
scripts/games/gh2_reputation.js (ES module, generated, do not hand-edit).

  REPUTATION_SECTIONS  [{ faction, value, section, requires? }]   from campaign.json reputationSections
                       faction = demons | merchants | guard, or 'any' for the city event card added at 13 with one faction;
                       requires = scenario numbers that must be completed too (the sheet's rows 12..14 say the same)

Usage:  python -I tools/extract-reputation.py [path/to/gloomhavensecretariat/data/gh2e]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT = os.path.join('D:' + os.sep, 'github', 'gloomhavensecretariat', 'data', 'gh2e')
OUT = os.path.join(ROOT, 'scripts', 'games', 'gh2_reputation.js')
FACTION = {'demons': 'demons', 'merchant-guild': 'merchants', 'military': 'guard', 'special': 'any'}


def main():
    base = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    with open(os.path.join(base, 'campaign.json'), encoding='utf-8') as f:
        rows = json.load(f)['reputationSections']
    out = []
    for r in rows:
        e = {'faction': FACTION[r['faction']], 'value': r['value'], 'section': r['section']}
        if r.get('requires'):
            e['requires'] = [int(n) for n in r['requires']]
        out.append(e)
    out.sort(key=lambda e: (e['faction'] == 'any', ['demons', 'merchants', 'guard', 'any'].index(e['faction']), e['value']))
    lines = [
        '// GENERATED by tools/extract-reputation.py from Gloomhaven Secretariat gh2e data (AGPL-3.0). Do not edit by hand.',
        '// Reputation unlocks: the section to read when a faction reaches a reputation value (and, where listed, the scenarios',
        '// that must be completed). The "any" row is the city event card added once one faction reaches the value.',
        '',
        'export const REPUTATION_SECTIONS = [',
    ]
    lines += ['  ' + json.dumps(e) + ',' for e in out]
    lines += ['];', '']
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('gh2_reputation.js', len(out), 'rows')


main()
