#!/usr/bin/env python3
"""Extract the class masteries (the two or three achievements per class that unlock the mastery perks) from the Gloomhaven Secretariat data.

Source (AGPL-3.0, mastery texts only): <secretariat>/data/<edition>/character/*.json and <edition>/label/en.json plus label/spoiler/en.json,
editions gh2e, mp (Mercenary Pack) and fh (Frosthaven). Jaws of the Lion has no masteries.
Output: scripts/games/masteries.js  (GENERATED, do not edit by hand): MASTERIES = { "<class name>": ["text", ...] }.
Icon placeholders are written as words (%game.damage:6% -> "damage 6").

Usage: python tools/extract-masteries.py [path to gloomhavensecretariat, default D:/github/gloomhavensecretariat]
"""
import glob, json, os, re, sys

root = sys.argv[1] if len(sys.argv) > 1 else 'D:/github/gloomhavensecretariat'

def walk(d, pre=''):
    for k, v in d.items():
        if isinstance(v, dict): yield from walk(v, pre + k + '.')
        else: yield pre + k, v

def labels(ed):
    out = {}
    for p in (f'label/en.json', f'label/spoiler/en.json'):
        f = os.path.join(root, 'data', ed, p)
        if os.path.exists(f): out.update(walk(json.load(open(f, encoding='utf-8'))))
    return out

def words(t):
    t = re.sub(r'<[^>]+>', '', t)
    def tok(m):
        parts = m.group(1).split(':')
        name = parts[0].split('.')[-1].replace('-', ' ')
        name = {'lost': 'lost', 'itemSlot': 'item slot'}.get(name, name)
        return name + (' ' + parts[1] if len(parts) > 1 else '')
    t = re.sub(r'%(?:game|data)\.([^%]+)%', lambda m: tok(m), t)
    return re.sub(r'\s+', ' ', t).strip()

out, missing = {}, []
for ed in ['gh2e', 'mp', 'fh']:
    L = labels(ed)
    for f in sorted(glob.glob(os.path.join(root, 'data', ed, 'character', '*.json'))):
        d = json.load(open(f, encoding='utf-8'))
        slug = os.path.basename(f)[:-5]
        name = L.get(f'character.{ed}.{slug}.') or L.get(f'character.{ed}.{slug}') or L.get(f'character.{slug}') or L.get(f'character.{ed}.{d.get("characterClass")}') or L.get(f'character.{d.get("characterClass")}')
        ms = d.get('masteries') or []
        texts = []
        for m in ms:
            k = m.strip('%').removeprefix('data.')
            t = L.get(k) or L.get(k.replace('custom.mastery.', f'custom.mp.')) 
            if t is None: missing.append((ed, slug, m)); continue
            texts.append(words(t))
        if name == 'HIVE': name = 'H.I.V.E.'
        if name and texts and name not in out: out[name] = texts
        elif ms and not name: missing.append((ed, slug, 'name'))

dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'scripts', 'games', 'masteries.js')
with open(dest, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// GENERATED by tools/extract-masteries.py from the Gloomhaven Secretariat data (AGPL-3.0). Do not edit by hand.\n')
    f.write('// MASTERIES[class name] = the achievements of the class (texts as printed, icons written as words).\n\n')
    f.write('export const MASTERIES = {\n')
    for k in sorted(out): f.write('  ' + json.dumps(k, ensure_ascii=False) + ': ' + json.dumps(out[k], ensure_ascii=False) + ',\n')
    f.write('};\n')
print('classes', len(out), 'missing', len(missing), missing[:6])
