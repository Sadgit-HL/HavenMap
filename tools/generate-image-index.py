#!/usr/bin/env python3
"""Writes scripts/images-index.js: every image the app uses, keyed by the path (or URL) the code asks for.

Input: tools/images-manifest.json (written when the images were converted and reorganised): one record per source file,
with the source path (a repo file or a file of the Wordhaven_Assets / worldhaven clones) and the file under images/.
The key is the source without its extension, the value is the file under images/ (also without the 'images/' prefix).
Remote addresses are the URLs the code used before (raw.githubusercontent.com), decoded.

Usage: python -I tools/generate-image-index.py
"""
import json
import os
import re
import sys
from urllib.parse import unquote

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, 'tools', 'images-manifest.json')
OUT = os.path.join(ROOT, 'scripts', 'images-index.js')

# local clone folder -> the address the code used for it
REMOTE = {
    'D:/github/Wordhaven_Assets/': 'https://raw.githubusercontent.com/Sadgit-HL/Wordhaven_Assets/refs/heads/main/',
    'D:/github/worldhaven/': 'https://raw.githubusercontent.com/any2cards/worldhaven/master/',
}
REPO_IMAGES = re.compile(r'^C:/Users/hansen/ai/games/HavenMap/HavenMap/images/')


def key_of(src):
    """The address the code asks for, decoded, without the file extension."""
    for prefix, url in REMOTE.items():
        if src.startswith(prefix):
            src = url + src[len(prefix):]
            break
    else:
        m = REPO_IMAGES.match(src)
        if m:
            src = 'images/' + src[m.end():]
        else:
            return None
    src = unquote(src)
    return re.sub(r'\.[A-Za-z0-9]+$', '', src)


def main():
    man = json.load(open(MANIFEST, encoding='utf-8'))
    index = {}
    skipped = 0
    for rec in man['files']:
        if rec['status'] != 'ok':
            skipped += 1
            continue
        key = key_of(rec['src'].replace('\\', '/'))
        if key is None:
            raise SystemExit('no key for ' + rec['src'])
        value = rec['dst']   # the file as it is under images/ (WebP, or SVG for the copied vector art)
        if key in index and index[key] != value:
            # the same address from two sources (a PNG and an SVG of one icon): the raster image is used
            if value.endswith('.svg') and not index[key].endswith('.svg'):
                continue
            if index[key].endswith('.svg') and not value.endswith('.svg'):
                index[key] = value
                continue
            raise SystemExit(f'key clash: {key} -> {index[key]} / {value}')
        index[key] = value
    lines = [
        '// GENERATED by tools/generate-image-index.py from tools/images-manifest.json. Do not edit by hand.',
        '// Image files under images/ by the address the code uses (path without extension, or the remote URL).',
        '// Use imageFile() in scripts/images.js; do not read this table directly.',
        'export const IMAGE_INDEX = {',
    ]
    for k in sorted(index):
        lines.append(f'  {json.dumps(k, ensure_ascii=False)}: {json.dumps(index[k], ensure_ascii=False)},')
    lines.append('};')
    lines.append('')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print(f'{len(index)} entries written; {skipped} manifest records skipped (missing or removed)')


if __name__ == '__main__':
    sys.exit(main())
